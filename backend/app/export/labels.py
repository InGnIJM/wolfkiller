def export_labels() -> dict[str, dict[str, str]]:
    """Return the bilingual label tables, with ``role.*`` keys from the catalog."""
    zh = dict(_ZH)
    en = dict(_EN)
    for role_id, meta in ROLE_METADATA.items():
        if not isinstance(meta, dict):
            continue
        name_zh = meta.get("name_zh")
        name_en = meta.get("name_en")
        if isinstance(name_zh, str) and name_zh:
            zh[f"role.{role_id}"] = name_zh
        if isinstance(name_en, str) and name_en:
            en[f"role.{role_id}"] = name_en
    return {"zh": zh, "en": en}
